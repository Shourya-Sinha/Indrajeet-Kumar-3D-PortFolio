import { z } from "zod";

export const loginSchema = z.object({
  email: z.string().email("Valid email address is required."),
  password: z.string().min(6, "Password is required."),
});

export const contactInquirySchema = z.object({
  fullName: z.string().trim().min(2, "Full name is required.").max(120),
  email: z.string().trim().email("Please provide a valid email address."),
  phone: z.string().trim().max(40).optional().or(z.literal("")),
  serviceCategory: z.string().trim().min(2, "Please select a service category.").max(120),
  budget: z.string().trim().max(80).optional().or(z.literal("")),
  preferredContactMethod: z
    .enum(["Email", "Phone", "WhatsApp", "LinkedIn"])
    .default("Email"),
  description: z
    .string()
    .trim()
    .min(10, "Please describe your project requirements (minimum 10 characters).")
    .max(5000),
});

export const resumePublishSchema = z.object({
  profileType: z
    .enum(["general", "fullstack", "mobile", "python-ai", "cybersecurity", "it-support"])
    .default("general"),
  version: z.string().trim().min(2).max(24).optional(),
  title: z.string().trim().min(2).max(160).optional(),
  description: z.string().trim().max(600).optional(),
  releaseNotes: z.string().trim().max(1000).optional(),
});

export const resumeRollbackSchema = z.object({
  profileType: z
    .enum(["general", "fullstack", "mobile", "python-ai", "cybersecurity", "it-support"])
    .default("general"),
  sourceVersion: z.string().trim().min(2),
});

export const resumeSettingsSchema = z.object({
  publishingMode: z.enum(["manual", "automatic"]),
  activeTemplateKey: z.string().trim().min(2).default("ats-classic-1.0"),
  autoGenerateDraftOnProfileChange: z.boolean().default(true),
  enabledRoleProfiles: z
    .array(z.enum(["general", "fullstack", "mobile", "python-ai", "cybersecurity", "it-support"]))
    .min(1),
});

export const userCreateSchema = z.object({
  email: z.string().trim().email(),
  name: z.string().trim().min(2).max(120),
  password: z.string().min(8, "Password must be at least 8 characters."),
  role: z.enum(["super_admin", "editor", "viewer"]).default("editor"),
  isActive: z.boolean().default(true),
});

export const userUpdateSchema = z.object({
  name: z.string().trim().min(2).max(120).optional(),
  password: z.string().min(8).optional(),
  role: z.enum(["super_admin", "editor", "viewer"]).optional(),
  isActive: z.boolean().optional(),
});
